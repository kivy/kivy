"""Metadata and verification steps for the copied macOS app's test bootstrap.

``osx_ci.sh`` runs app inspection with the bundled app Python, and wheel/version
validation with the external tools Python. Keep third-party imports inside the
validation functions so app inspection works before dev dependencies exist.
"""

import argparse
from hashlib import sha256
from importlib import import_module, metadata, util
import json
import os
from pathlib import Path
import platform
import sys
import sysconfig
import tomllib


def write_json(path, value):
    path.write_text(
        json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def verify_app_venv(app):
    """Check the install destination before pip can modify the copied app."""
    venv = app / "Contents/Resources/venv"
    if Path(sys.prefix).resolve() != venv:
        raise SystemExit(f"App Python is not using the copied venv: {sys.prefix}")
    purelib = Path(sysconfig.get_path("purelib")).resolve()
    if not purelib.is_relative_to(venv):
        raise SystemExit(f"pip would install outside the copied venv: {purelib}")


def hash_package_files(package):
    """Ignore generated bytecode when comparing the installed Kivy contents."""
    hashes = {}
    for path in sorted(package.rglob("*")):
        if (not path.is_file() or "__pycache__" in path.parts
                or path.suffix in {".pyc", ".pyo"}):
            continue
        hashes[str(path.relative_to(package))] = sha256(
            path.read_bytes()).hexdigest()
    return hashes


def snapshot_kivy(app, output):
    """Record Kivy's origin, version and files to detect bootstrap replacement."""
    app = app.resolve()
    verify_app_venv(app)
    spec = util.find_spec("kivy")
    if spec is None or spec.origin is None:
        raise SystemExit("Kivy is not installed in the copied app")
    package = Path(spec.origin).resolve().parent
    if not package.is_relative_to(app):
        raise SystemExit(f"Kivy imports from outside the copied app: {package}")
    distribution = metadata.distribution("Kivy")
    if Path(distribution.locate_file("kivy")).resolve() != package:
        raise SystemExit("Kivy's distribution metadata and import path disagree")
    files = hash_package_files(package)
    extensions = [name for name in files if name.endswith((".so", ".pyd"))]
    if not extensions:
        raise SystemExit("The copied Kivy installation has no compiled extensions")
    write_json(output, {
        "version": distribution.version,
        "package": str(package),
        "files": files,
    })
    print("App Python:", sys.executable, sys.version, flush=True)
    print("App prefixes:", sys.prefix, sys.base_prefix, flush=True)
    print("Bundled Kivy:", distribution.version, package,
          f"({len(extensions)} compiled extensions)", flush=True)


def write_dev_requirements(pyproject, output):
    """Read the canonical dev extra without invoking Kivy's build backend."""
    with pyproject.open("rb") as stream:
        project = tomllib.load(stream)
    requirements = project["project"]["optional-dependencies"]["dev"]
    if not requirements:
        raise SystemExit("Kivy's dev dependency list is empty")
    output.write_text("\n".join(requirements) + "\n", encoding="utf-8")


def verify_tools_environment(venv, python_version):
    """Ensure resolution uses the app's Python version in an independent venv."""
    if Path(sys.prefix).resolve() != venv.resolve():
        raise SystemExit(
            f"Preparation tools are using the wrong venv: {sys.prefix}")
    if platform.python_version() != python_version:
        raise SystemExit("Preparation tools and app Python versions differ")
    if "PYTHONHOME" in os.environ or "PYTHONPATH" in os.environ:
        raise SystemExit("App Python environment leaked into preparation tools")
    print("Preparation Python:", sys.executable, sys.version, flush=True)
    print("Preparation prefixes:", sys.prefix, sys.base_prefix, flush=True)


def applicable_requirements(path):
    """Evaluate markers with the bundled-Python tools environment."""
    from packaging.requirements import Requirement

    for line in path.read_text("utf-8").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        requirement = Requirement(line)
        if requirement.marker is None or requirement.marker.evaluate():
            yield requirement


def read_dependency_pins(path):
    """Require exact dependency-only pins before the no-deps installation."""
    from packaging.utils import canonicalize_name
    from packaging.version import Version

    pins = {}
    for requirement in applicable_requirements(path):
        name = canonicalize_name(requirement.name)
        specifiers = list(requirement.specifier)
        if (name == "kivy" or requirement.url or requirement.extras
                or len(specifiers) != 1 or specifiers[0].operator != "=="
                or "*" in specifiers[0].version):
            raise SystemExit(
                f"Expected a dependency-only exact pin: {requirement}")
        if name in pins:
            raise SystemExit(f"Duplicate resolved dependency: {name}")
        Version(specifiers[0].version)
        pins[name] = requirement
    if not pins:
        raise SystemExit("No applicable development dependencies were resolved")
    return pins


def validate_prepared_wheels(work):
    """Require a complete, compatible wheel set before modifying the test app."""
    from packaging.tags import compatible_tags, cpython_tags, mac_platforms
    from packaging.utils import canonicalize_name, parse_wheel_filename
    from packaging.version import Version

    pins = read_dependency_pins(work / "dev.txt")
    platforms = list(mac_platforms(version=(11, 0), arch="universal2"))
    allowed_platforms = set(platforms) | {"any"}
    supported = set(cpython_tags(platforms=platforms))
    interpreter = f"cp{sys.version_info.major}{sys.version_info.minor}"
    supported.update(compatible_tags(
        interpreter=interpreter, platforms=platforms))
    selected = {}
    for wheel in sorted((work / "wheels").iterdir()):
        if not wheel.is_file() or wheel.suffix != ".whl":
            raise SystemExit(f"Expected a prepared wheel, not an sdist: {wheel}")
        name, version, _, tags = parse_wheel_filename(wheel.name)
        if name == "kivy" or name not in pins:
            raise SystemExit(f"Unexpected prepared distribution: {wheel.name}")
        if (not tags.intersection(supported)
                or any(tag.platform not in allowed_platforms for tag in tags)):
            raise SystemExit(f"Wheel is not compatible with the app: {wheel.name}")
        if version not in pins[name].specifier:
            raise SystemExit(
                f"Wheel does not satisfy its resolved pin: {wheel.name}")
        if name in selected:
            raise SystemExit(f"Multiple prepared wheels for {name}")
        selected[name] = {
            "name": name, "version": str(version), "filename": wheel.name,
        }

    missing = pins.keys() - selected.keys()
    if missing:
        raise SystemExit(f"Missing prepared wheels: {', '.join(sorted(missing))}")
    for requirement in applicable_requirements(work / "dev.in"):
        name = canonicalize_name(requirement.name)
        if (requirement.url or name not in selected
                or Version(selected[name]["version"])
                not in requirement.specifier):
            raise SystemExit(f"Resolved graph does not satisfy {requirement}")
    manifest = [selected[name] for name in sorted(selected)]
    write_json(work / "selected-wheels.json", manifest)
    print(f"Validated {len(manifest)} universal2/platform-independent wheels")


def record_installed_dependencies(app, work):
    """Inspect actual app-side distributions for the tools-side version check."""
    app = app.resolve()
    selected = json.loads((work / "selected-wheels.json").read_text("utf-8"))
    installed = {}
    for wheel in selected:
        distribution = metadata.distribution(wheel["name"])
        location = Path(distribution.locate_file("")).resolve()
        if not location.is_relative_to(app):
            raise SystemExit(
                f"Dependency imports from outside the app: {location}")
        installed[wheel["name"]] = {
            "version": distribution.version, "location": str(location),
        }
        print("Development dependency:", wheel["name"], distribution.version,
              location, flush=True)
    write_json(work / "installed-dev.json", installed)


def verify_installed_versions(work):
    """Compare installed versions using packaging from the external tools venv."""
    from packaging.version import Version

    selected = json.loads((work / "selected-wheels.json").read_text("utf-8"))
    installed = json.loads((work / "installed-dev.json").read_text("utf-8"))
    for wheel in selected:
        actual = installed[wheel["name"]]["version"]
        if Version(actual) != Version(wheel["version"]):
            raise SystemExit(
                f"Incorrect installed version for {wheel['name']}: {actual}")
    print(f"Verified {len(selected)} installed development dependencies")


def inspect_installed_native_dependencies(app, work):
    """Check Mach-O files owned by the resolved development distributions."""
    from osx_binary_checks import inspect_macho_binary, is_macho

    app = app.resolve()
    selected = json.loads((work / "selected-wheels.json").read_text("utf-8"))
    report = {"complete": False, "binaries": []}
    checked = set()
    try:
        for wheel in selected:
            distribution = metadata.distribution(wheel["name"])
            if distribution.files is None:
                raise ValueError(f"Missing installed file list for {wheel['name']}")
            for relative in distribution.files:
                binary = Path(distribution.locate_file(relative)).resolve()
                if not binary.is_file():
                    continue
                if not binary.is_relative_to(app):
                    raise ValueError(f"Dependency file outside the app: {binary}")
                if binary in checked or not is_macho(binary):
                    continue
                check = inspect_macho_binary(binary, "11.0")
                check["distribution"] = wheel["name"]
                report["binaries"].append(check)
                checked.add(binary)
        report["complete"] = True
    finally:
        write_json(work / "native-dev-binaries.json", report)
    print(f"Verified {len(checked)} installed development Mach-O binaries")


def verify_installed_tests(app):
    """Prove the bootstrapped app can discover its installed test package."""
    tests = import_module("kivy.tests")
    test_path = Path(tests.__path__[0]).resolve()
    if not test_path.is_relative_to(app.resolve()):
        raise SystemExit(
            f"Tests imported from outside the copied app: {test_path}")
    print("Installed tests:", test_path, flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)

    snapshot = commands.add_parser(
        "snapshot-kivy", help="Record the bundled Kivy files before/after pip")
    snapshot.add_argument("app", type=Path)
    snapshot.add_argument("output", type=Path)

    requirements = commands.add_parser(
        "write-requirements", help="Extract the canonical dev requirements")
    requirements.add_argument("pyproject", type=Path)
    requirements.add_argument("output", type=Path)

    tools = commands.add_parser(
        "verify-tools", help="Check the external bundled-Python tools venv")
    tools.add_argument("venv", type=Path)
    tools.add_argument("python_version")

    wheels = commands.add_parser(
        "validate-wheels", help="Check prepared wheels against resolved pins")
    wheels.add_argument("work", type=Path)

    installed = commands.add_parser(
        "record-installed", help="Record the app's installed dependency versions")
    installed.add_argument("app", type=Path)
    installed.add_argument("work", type=Path)

    versions = commands.add_parser(
        "verify-installed", help="Compare app versions with the resolved pins")
    versions.add_argument("work", type=Path)

    native = commands.add_parser(
        "inspect-native", help="Check installed development Mach-O binaries")
    native.add_argument("app", type=Path)
    native.add_argument("work", type=Path)

    tests = commands.add_parser(
        "verify-tests", help="Import the copied app's installed test package")
    tests.add_argument("app", type=Path)

    args = parser.parse_args()
    if args.command == "snapshot-kivy":
        snapshot_kivy(args.app, args.output)
    elif args.command == "write-requirements":
        write_dev_requirements(args.pyproject, args.output)
    elif args.command == "verify-tools":
        verify_tools_environment(args.venv, args.python_version)
    elif args.command == "validate-wheels":
        validate_prepared_wheels(args.work)
    elif args.command == "record-installed":
        record_installed_dependencies(args.app, args.work)
    elif args.command == "verify-installed":
        verify_installed_versions(args.work)
    elif args.command == "inspect-native":
        inspect_installed_native_dependencies(args.app, args.work)
    elif args.command == "verify-tests":
        verify_installed_tests(args.app)


if __name__ == "__main__":
    main()
