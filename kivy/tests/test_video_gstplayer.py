'''
GStreamer video provider tests
==============================

Integration tests for kivy.lib.gstplayer and the ``gstplayer`` video
provider. They need a GStreamer runtime with gst-plugins-base and -good
(``videotestsrc``, ``vp8enc``, ``webmmux``, ``matroskademux``,
``vp8dec``) and skip otherwise. No video file is committed: clips are
generated by GStreamer itself, with VP8 in WebM.
'''

import os
import time
import unittest

import pytest

from kivy.tests.common import GraphicUnitTest


def _gst():
    try:
        from kivy.lib import gstplayer
        gstplayer.GstPlayer
    except ImportError as e:
        pytest.skip('no usable GStreamer: {}'.format(e),
                    allow_module_level=True)
    state, error = gstplayer.init_wait(120)
    if state != 'ok':
        pytest.skip('GStreamer failed to initialize: {}'.format(error),
                    allow_module_level=True)
    for name in ('playbin3', 'videotestsrc', 'vp8enc', 'webmmux',
                 'matroskademux', 'vp8dec', 'appsink'):
        if not gstplayer.element_available(name):
            pytest.skip('GStreamer element {} missing'.format(name),
                        allow_module_level=True)
    return gstplayer


g = _gst()

# 60 frames at 30 fps (2 s), 320x240.
_CLIPS = {
    'smpte': 'videotestsrc num-buffers=60 pattern=smpte',
    'red': 'videotestsrc num-buffers=60 pattern=red',
}
_clip_dir = None


def clip(name):
    '''Path of a generated test clip.'''
    global _clip_dir
    import tempfile
    if _clip_dir is None:
        _clip_dir = tempfile.mkdtemp(prefix='kivy-gst-test-')
    path = os.path.join(_clip_dir, name + '.webm')
    if not os.path.exists(path):
        location = path.replace('\\', '/')
        err = g.run_pipeline(
            '{} ! video/x-raw,width=320,height=240,framerate=30/1 ! '
            'videoconvert ! vp8enc deadline=1 ! webmmux ! '
            'filesink location="{}"'.format(_CLIPS[name], location))
        if err is not None:
            pytest.skip('cannot generate a test clip: {}'.format(err))
    return path


def drive(player, until, timeout=10.0, preroll=False):
    '''Poll a GstPlayer the way the provider does until `until(messages)`
    returns True. Returns every message seen.'''
    seen = []
    end = time.monotonic() + timeout
    while time.monotonic() < end:
        msgs = player.pop_messages()
        seen.extend(msgs)
        if until(seen):
            return seen
        time.sleep(0.005)
    raise AssertionError('timed out; messages: {!r}'.format(seen[-10:]))


def kinds(messages):
    return [m[0] for m in messages]


class GstPlayerCoreTestCase(unittest.TestCase):
    '''The core without a window (rgba and nv12 sinks, frames pulled but
    not uploaded).'''

    def make(self, path, sink='nv12', **kw):
        uri = path if '://' in path else g.filename_to_uri(path)
        p = g.GstPlayer(uri, sink=sink, **kw)
        self.addCleanup(p.teardown)
        p.build()
        return p

    def test_preroll_frame_without_playing(self):
        p = self.make(clip('smpte'))
        p.set_state(g.STATE_PAUSED)
        drive(p, lambda m: 'async-done' in kinds(m))
        self.assertTrue(p.pull(preroll=True))
        self.assertEqual((p.width, p.height), (320, 240))
        self.assertEqual(p.format, 'NV12')
        self.assertAlmostEqual(p.duration(), 2.0, delta=0.1)

    def test_plays_to_eos(self):
        p = self.make(clip('smpte'), sink='rgba')
        p.set_state(g.STATE_PLAYING)
        frames = []

        def until(m):
            if p.pull():
                frames.append(1)
            return 'eos' in kinds(m)
        drive(p, until)
        self.assertGreater(len(frames), 30)
        self.assertEqual(p.format, 'RGBA')

    def test_paused_seek(self):
        p = self.make(clip('smpte'))
        p.set_state(g.STATE_PAUSED)
        drive(p, lambda m: 'async-done' in kinds(m))
        self.assertTrue(p.seek(1.0, True))
        drive(p, lambda m: 'async-done' in kinds(m))
        self.assertTrue(p.pull(preroll=True))
        self.assertAlmostEqual(p.position(), 1.0, delta=0.1)

    def test_seek_from_eos_restarts(self):
        p = self.make(clip('smpte'))
        p.set_state(g.STATE_PLAYING)
        # appsink posts EOS once its queued sample has been taken.
        drive(p, lambda m: p.pull() and False or 'eos' in kinds(m))
        self.assertTrue(p.seek(0.0, True))
        frames = []

        def until(m):
            if p.pull():
                frames.append(p.position())
            return len(frames) > 5
        drive(p, until)
        self.assertLess(frames[0], 0.5)

    def test_two_players(self):
        # Software decoders: two D3D12 VP8 decoders at once failed on
        # Windows ("No valid frames decoded"), a driver/decoder matter.
        a = self.make(clip('smpte'), force_sw_decoders=True)
        b = self.make(clip('red'), force_sw_decoders=True)
        for p in (a, b):
            p.set_state(g.STATE_PAUSED)
        for p in (a, b):
            drive(p, lambda m: 'async-done' in kinds(m))
            self.assertTrue(p.pull(preroll=True))

    def test_missing_file_error(self):
        from kivy.lib.gstplayer._policy import BusError, error_text
        p = self.make(os.path.join(os.path.dirname(clip('smpte')),
                                   'does-not-exist.webm'))
        p.set_state(g.STATE_PAUSED)
        msgs = drive(p, lambda m: 'error' in kinds(m))
        errors = [BusError(*m[1:]) for m in msgs if m[0] == 'error']
        self.assertTrue(error_text(errors))
        self.assertIn('resource', errors[0].domain)

    def test_not_a_video_error(self):
        path = os.path.join(os.path.dirname(clip('smpte')), 'text.webm')
        with open(path, 'w') as f:
            f.write('this is not a video\n' * 50)
        p = self.make(path)
        p.set_state(g.STATE_PAUSED)
        drive(p, lambda m: 'error' in kinds(m))

    def test_audio_only_player(self):
        p = self.make(clip('smpte'), sink=None)
        self.assertFalse(p.pull())

    def test_teardown_twice(self):
        p = self.make(clip('smpte'))
        p.set_state(g.STATE_PAUSED)
        p.teardown()
        p.teardown()
        self.assertEqual(p.pop_messages(), [])
        self.assertEqual(p.position(), -1.0)

    def test_describe(self):
        p = self.make(clip('smpte'))
        p.set_state(g.STATE_PAUSED)
        drive(p, lambda m: 'async-done' in kinds(m))
        self.assertTrue(p.describe()['decoder'])


class VideoGstplayerTestCase(GraphicUnitTest):
    '''The provider, with a window (nv12 and rgba paths).'''

    def make(self, path, **options):
        from kivy.core.video.video_gstplayer import VideoGstplayer
        v = VideoGstplayer(filename=path, options=options)
        self.addCleanup(v.unload)
        return v

    def pump(self, until, timeout=10.0):
        end = time.monotonic() + timeout
        while time.monotonic() < end:
            self.advance_frames(1)
            if until():
                return True
            time.sleep(0.005)
        return False

    def center_rgb(self, texture):
        from kivy.graphics import Fbo, Rectangle
        fbo = Fbo(size=(8, 8))
        with fbo:
            Rectangle(size=(8, 8), texture=texture)
        fbo.draw()
        px = fbo.pixels
        i = (4 * 8 + 4) * 4
        return px[i], px[i + 1], px[i + 2]

    def check_first_frame(self, render):
        v = self.make(clip('red'), render=render)
        loaded = []
        v.bind(on_load=lambda *a: loaded.append(v.state))
        self.assertTrue(self.pump(lambda: loaded), 'no on_load')
        self.assertEqual(loaded[0], '')          # shown without playing
        self.assertEqual(v.texture.size, (320, 240))
        r, gr, b = self.center_rgb(v.texture)
        self.assertGreater(r, 200)
        self.assertLess(gr, 60)
        self.assertLess(b, 60)
        return v

    def test_first_frame_nv12(self):
        self.check_first_frame('nv12')

    def test_first_frame_rgba(self):
        self.check_first_frame('rgba')

    def test_first_frame_auto(self):
        v = self.check_first_frame('auto')
        self.assertEqual(v._path, 'nv12')

    def test_play_eos_stop(self):
        v = self.make(clip('smpte'), render='nv12')
        eos = []
        v.bind(on_eos=lambda *a: eos.append(1))
        v.play()
        self.assertTrue(self.pump(lambda: eos, 10))
        self.assertEqual(v.state, '')

    def test_loop(self):
        v = self.make(clip('smpte'), render='nv12')
        v.eos = 'loop'
        eos = []
        v.bind(on_eos=lambda *a: eos.append(1))
        v.play()
        self.assertTrue(self.pump(lambda: len(eos) >= 2, 15))
        self.assertEqual(v.state, 'playing')

    def test_seek_while_paused_updates_position(self):
        v = self.make(clip('smpte'), render='nv12')
        self.assertTrue(self.pump(lambda: v.texture is not None))
        v.seek(0.5)
        self.assertTrue(self.pump(lambda: v._seeks.pending is None))
        self.assertAlmostEqual(v.position, 1.0, delta=0.15)

    def test_missing_file_on_error_once(self):
        v = self.make(os.path.join(os.path.dirname(clip('smpte')),
                                   'nope.webm'))
        errors = []
        v.bind(on_error=lambda c, e: errors.append(e))
        v.play()
        self.assertTrue(self.pump(lambda: errors))
        self.pump(lambda: False, 0.5)
        self.assertEqual(len(errors), 1)
        self.assertEqual(v.state, '')
        self.assertFalse(v.buffering)

    def test_unknown_option_warned(self):
        from unittest import mock
        from kivy.core.video import video_gstplayer
        with mock.patch.object(video_gstplayer, 'Logger') as logger:
            v = video_gstplayer.VideoGstplayer(
                filename=None, options={'eos': 'loop', 'nope': 1})
        self.addCleanup(v.unload)
        logger.warning.assert_called_once()
        self.assertIn('nope', logger.warning.call_args[0][0])

    def _corner_colours(self, texture):
        '''Colours near the four corners (BL, BR, TR, TL) on an 8x8 grid.'''
        from kivy.graphics import Fbo, Rectangle
        fbo = Fbo(size=(8, 8))
        with fbo:
            Rectangle(size=(8, 8), texture=texture)
        fbo.draw()
        px = fbo.pixels

        def at(x, y):
            i = (y * 8 + x) * 4
            return tuple(px[i:i + 3])
        return [at(1, 1), at(6, 1), at(6, 6), at(1, 6)]

    def test_rotation_tag(self):
        enc = next((e for e in ('x264enc', 'openh264enc')
                    if g.element_available(e)), None)
        if enc is None or not g.element_available('mp4mux') or \
                not g.element_available('taginject'):
            self.skipTest('needs an H.264 encoder, mp4mux and taginject')
        d = os.path.dirname(clip('smpte'))
        paths = {}
        for tag in ('rotate-0', 'rotate-90'):
            paths[tag] = os.path.join(d, tag + '.mp4')
            err = g.run_pipeline(
                'videotestsrc num-buffers=10 pattern=smpte ! '
                'video/x-raw,width=320,height=180,framerate=30/1 ! '
                'videoconvert ! video/x-raw,format=I420 ! '
                'taginject tags="image-orientation={}" ! {} ! h264parse ! '
                'mp4mux ! filesink location="{}"'.format(
                    tag, enc, paths[tag].replace('\\', '/')))
            if err:
                self.skipTest('cannot make the clip: ' + err)
        upright = self.make(paths['rotate-0'], render='nv12')
        self.assertTrue(self.pump(lambda: upright.texture is not None))
        base = self._corner_colours(upright.texture)
        for render in ('nv12', 'rgba'):
            v = self.make(paths['rotate-90'], render=render)
            self.assertTrue(self.pump(
                lambda: v.texture is not None and
                v._orientation == 'rotate-90'))
            self.pump(lambda: tuple(v.texture.size) == (180, 320), 2)
            self.assertEqual(tuple(v.texture.size), (180, 320))
            # Turned clockwise: the picture's top-left is now top-right.
            got = self._corner_colours(v.texture)
            for out, src in zip(range(4), (1, 2, 3, 0)):
                for k in range(3):
                    self.assertLess(abs(got[out][k] - base[src][k]), 40,
                                    (render, got, base))

    def test_pixel_aspect_ratio(self):
        path = os.path.join(os.path.dirname(clip('smpte')), 'par.webm')
        err = g.run_pipeline(
            'videotestsrc num-buffers=10 pattern=smpte ! '
            'video/x-raw,width=320,height=180,framerate=30/1,'
            'pixel-aspect-ratio=2/1 ! videoconvert ! vp8enc deadline=1 ! '
            'webmmux ! filesink location="{}"'.format(path.replace('\\', '/')))
        if err:
            self.skipTest('cannot make the clip: ' + err)
        for render in ('nv12', 'rgba'):
            v = self.make(path, render=render)
            self.assertTrue(self.pump(lambda: v.texture is not None))
            self.assertEqual(tuple(v.texture.size), (640, 180))

    def test_thumbnail(self):
        from kivy.core.video.video_gstplayer import VideoGstplayer
        tex = VideoGstplayer.generate_thumbnail(clip('smpte'), 1.0)
        self.assertIsNotNone(tex)
        self.assertEqual(tex.size, (320, 240))
        small = VideoGstplayer.generate_thumbnail(clip('smpte'), 0.5,
                                                  size=(64, 48))
        self.assertEqual(small.size, (64, 48))
        self.assertIsNone(VideoGstplayer.generate_thumbnail(
            os.path.join(os.path.dirname(clip('smpte')), 'nope.webm'), 0))
